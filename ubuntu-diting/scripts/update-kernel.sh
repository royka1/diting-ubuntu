#!/bin/bash
# Move kernel.lock to the newest stable release after verifying its signed
# tag. Rebases the local patch branch and re-exports kernel/patches.
# Deliberate, interactive step; never called by 'make image'.
. "$(dirname "$0")/lib.sh"
need curl python3 git gpg
new="${1:-$(curl -fsS https://www.kernel.org/releases.json |
	python3 -c 'import json,sys; print(json.load(sys.stdin)["latest_stable"]["version"])')}"
[ "$new" != "$KERNEL_VERSION" ] || { log "already at $new"; exit 0; }
case "$new" in *-rc*) die "refusing release candidate $new" ;; esac

git -C "$KERNEL_GIT" fetch --depth 1 origin tag "v$new"
export GNUPGHOME="$KERNEL_DIR/.gnupg"
status="$(LC_ALL=C git -C "$KERNEL_GIT" verify-tag --raw "v$new" 2>&1 || true)"
fpr="$(sed -n 's/^\[GNUPG:\] VALIDSIG \([0-9A-F]*\) .*/\1/p' <<<"$status" | head -1)"
[ -n "$fpr" ] || die "tag v$new signature not valid:\n$status"
tagobj="$(git -C "$KERNEL_GIT" rev-parse "v$new")"
commit="$(git -C "$KERNEL_GIT" rev-parse "v$new^{commit}")"
date="$(git -C "$KERNEL_GIT" log -1 --format=%cs "$commit")"
major="${new%%.*}"
sha="$(curl -fsS "https://cdn.kernel.org/pub/linux/kernel/v$major.x/sha256sums.asc" |
	awk -v f="linux-$new.tar.xz" '$2 == f {print $1}')"

branch="diting/v$new"
log "rebasing patches onto v$new as $branch"
git -C "$KERNEL_GIT" switch -c "$branch" "diting/v$KERNEL_VERSION"
git -C "$KERNEL_GIT" rebase --onto "v$new" "v$KERNEL_VERSION" ||
	die "rebase conflicts in $KERNEL_GIT; resolve, then rerun export (kernel.lock unchanged)"
rm -f "$KERNEL_PATCHES"/*.patch
git -C "$KERNEL_GIT" format-patch -q --no-signature --zero-commit -o "$KERNEL_PATCHES" "v$new..$branch"

cat > "$UD/config/kernel.lock" <<L
# Locked upstream stable kernel. Generated by update-kernel.sh; edit only via
# \`make update-kernel\`. make image never changes this file.
KERNEL_VERSION=$new
KERNEL_RELEASE_DATE=$date
KERNEL_GIT_URL=$KERNEL_GIT_URL
KERNEL_TAG=v$new
KERNEL_TAG_OBJECT=$tagobj
KERNEL_COMMIT=$commit
# Signed tag, verified with \`git verify-tag\` (GOODSIG/VALIDSIG)
KERNEL_TAG_SIGNER_FPR=$fpr
KERNEL_TARBALL_URL=https://cdn.kernel.org/pub/linux/kernel/v$major.x/linux-$new.tar.xz
KERNEL_TARBALL_SHA256=${sha:-UNKNOWN}
KERNEL_LOCKED_ON=$(date -u +%F)
L
log "kernel.lock now at $new ($commit); rebuild with 'make kernel' and re-run tests"
